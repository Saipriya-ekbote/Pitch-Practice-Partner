"""
Data models for Voice Interaction and Speech Intelligence (Phase 8).
Encompasses audio payloads, speech-to-text results, text-to-speech results,
and objective speech metrics.
"""

from dataclasses import dataclass, field
from typing import Optional, Dict, Any


@dataclass
class AudioData:
    """
    In-memory representation of recorded or uploaded speech audio.
    Raw audio bytes remain strictly temporary and are never stored in SQLite or committed.

    Attributes:
        raw_bytes: Raw audio byte stream.
        audio_format: Audio container/encoding format ('wav', 'webm', 'mp3', 'ogg').
        sample_rate: Audio sampling frequency in Hz (default 16000).
        duration_seconds: Actual recording duration in seconds, if known.
    """
    raw_bytes: bytes
    audio_format: str = "wav"
    sample_rate: int = 16000
    duration_seconds: Optional[float] = None

    def __post_init__(self) -> None:
        if not isinstance(self.raw_bytes, (bytes, bytearray)):
            raise ValueError("AudioData 'raw_bytes' must be bytes or bytearray.")
        if self.duration_seconds is not None and self.duration_seconds < 0.0:
            raise ValueError("AudioData 'duration_seconds' cannot be negative.")

    @property
    def size_bytes(self) -> int:
        """Return byte size of the raw audio."""
        return len(self.raw_bytes)


@dataclass
class STTResult:
    """
    Result of a speech-to-text transcription.

    Attributes:
        text: Transcribed text string.
        confidence: Transcription confidence score between 0.0 and 1.0 (if available).
        duration_seconds: Audio recording duration in seconds, if known.
        is_simulated: Flag indicating whether transcription was generated by a demo/simulated provider.
        error: Optional error description if transcription encountered an issue.
    """
    text: str = ""
    confidence: Optional[float] = None
    duration_seconds: Optional[float] = None
    is_simulated: bool = False
    error: Optional[str] = None

    def __post_init__(self) -> None:
        if self.confidence is not None and not (0.0 <= self.confidence <= 1.0):
            raise ValueError(f"STTResult 'confidence' {self.confidence} must be between 0.0 and 1.0.")
        if self.duration_seconds is not None and self.duration_seconds < 0.0:
            raise ValueError("STTResult 'duration_seconds' cannot be negative.")

    def to_dict(self) -> Dict[str, Any]:
        """Convert STTResult to dictionary."""
        return {
            "text": self.text,
            "confidence": round(self.confidence, 3) if self.confidence is not None else None,
            "duration_seconds": round(self.duration_seconds, 2) if self.duration_seconds is not None else None,
            "is_simulated": self.is_simulated,
            "error": self.error,
        }


@dataclass
class TTSResult:
    """
    Result of a text-to-speech audio synthesis.

    Attributes:
        audio_bytes: Synthesized audio byte stream.
        audio_format: Format/MIME type of synthesized audio ('audio/wav', 'audio/mp3').
        duration_seconds: Playback duration in seconds, if known.
        error: Optional error description if synthesis encountered an issue.
    """
    audio_bytes: bytes = b""
    audio_format: str = "audio/wav"
    duration_seconds: Optional[float] = None
    error: Optional[str] = None

    def __post_init__(self) -> None:
        if not isinstance(self.audio_bytes, (bytes, bytearray)):
            raise ValueError("TTSResult 'audio_bytes' must be bytes or bytearray.")
        if self.duration_seconds is not None and self.duration_seconds < 0.0:
            raise ValueError("TTSResult 'duration_seconds' cannot be negative.")

    @property
    def size_bytes(self) -> int:
        """Return byte size of the synthesized audio."""
        return len(self.audio_bytes)


@dataclass
class SpeechMetrics:
    """
    Objective, factual speech delivery measurements.
    Strictly avoids psychological, emotional, honesty, or personality diagnoses.

    Attributes:
        recording_duration_seconds: Actual recording duration in seconds, if reliably available.
        word_count: Total words in the transcribed speech.
        words_per_minute: Speaking rate (WPM) calculated strictly using recording duration.
        confidence: Transcription confidence score (if provided by STT).
        filler_count: Total vocal filler words detected via Phase 4 intelligence detectors.
        filler_percentage: Filler words as a percentage of total words.
        is_simulated: Flag indicating whether metrics derive from demo/simulated audio.
    """
    recording_duration_seconds: Optional[float] = None
    word_count: int = 0
    words_per_minute: Optional[float] = None
    confidence: Optional[float] = None
    filler_count: int = 0
    filler_percentage: float = 0.0
    is_simulated: bool = False

    def __post_init__(self) -> None:
        if self.recording_duration_seconds is not None and self.recording_duration_seconds < 0.0:
            raise ValueError("SpeechMetrics 'recording_duration_seconds' cannot be negative.")
        if self.word_count < 0:
            raise ValueError("SpeechMetrics 'word_count' cannot be negative.")
        if self.words_per_minute is not None and self.words_per_minute < 0.0:
            raise ValueError("SpeechMetrics 'words_per_minute' cannot be negative.")
        if self.confidence is not None and not (0.0 <= self.confidence <= 1.0):
            raise ValueError("SpeechMetrics 'confidence' must be between 0.0 and 1.0.")

    def to_dict(self) -> Dict[str, Any]:
        """Convert SpeechMetrics to dictionary."""
        return {
            "recording_duration_seconds": round(self.recording_duration_seconds, 2) if self.recording_duration_seconds is not None else None,
            "word_count": self.word_count,
            "words_per_minute": round(self.words_per_minute, 1) if self.words_per_minute is not None else None,
            "confidence": round(self.confidence, 3) if self.confidence is not None else None,
            "filler_count": self.filler_count,
            "filler_percentage": round(self.filler_percentage, 1),
            "is_simulated": self.is_simulated,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any]) -> "SpeechMetrics":
        """Construct SpeechMetrics from dictionary."""
        conf = data.get("confidence")
        rec_dur = data.get("recording_duration_seconds")
        wpm = data.get("words_per_minute")
        return cls(
            recording_duration_seconds=float(rec_dur) if rec_dur is not None else None,
            word_count=int(data.get("word_count", 0)),
            words_per_minute=float(wpm) if wpm is not None else None,
            confidence=float(conf) if conf is not None else None,
            filler_count=int(data.get("filler_count", 0)),
            filler_percentage=float(data.get("filler_percentage", 0.0)),
            is_simulated=bool(data.get("is_simulated", False)),
        )
